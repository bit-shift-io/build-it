-- The code panel's text buffer (src/game/text_buffer.lua): pure editing
-- of lines of text with a cursor and an optional selection.
local TextBuffer = require("src.game.text_buffer")

test("typing inserts at the cursor and the text reads back", function()
	local buf = TextBuffer.new("return box{}")
	TextBuffer.place(buf, 1, 10)
	TextBuffer.insert(buf, "{ }")
	assertEqual("return box{ }{}", TextBuffer.text(buf))
end)

test("a newline splits the line; pasted lines (CRLF too) land with the cursor after them", function()
	local buf = TextBuffer.new("ab")
	TextBuffer.place(buf, 1, 1)
	TextBuffer.insert(buf, "\n")
	assertEqual("a\nb", TextBuffer.text(buf))
	assertEqual(2, buf.line)
	assertEqual(0, buf.col)
	TextBuffer.insert(buf, "x\r\ny\r\nz")
	assertEqual("a\nx\ny\nzb", TextBuffer.text(buf))
	assertEqual(4, buf.line)
	assertEqual(1, buf.col)
end)

test("backspace and delete remove one character, joining lines at the ends", function()
	local buf = TextBuffer.new("a\195\169\nbc")
	TextBuffer.place(buf, 1, 3)
	TextBuffer.backspace(buf)
	assertEqual("a\nbc", TextBuffer.text(buf), "a UTF-8 character goes whole")
	TextBuffer.delete(buf)
	assertEqual("abc", TextBuffer.text(buf))
	TextBuffer.place(buf, 1, 0)
	TextBuffer.backspace(buf)
	assertEqual("abc", TextBuffer.text(buf), "nothing before the start")
	TextBuffer.place(buf, 1, 3)
	TextBuffer.delete(buf)
	assertEqual("abc", TextBuffer.text(buf), "nothing after the end")
end)

test("a selection copies, cuts, and is replaced by typing", function()
	local buf = TextBuffer.new("one\ntwo\nthree")
	TextBuffer.place(buf, 3, 2)
	TextBuffer.place(buf, 1, 1, true)
	assertEqual("ne\ntwo\nth", TextBuffer.selected(buf), "selected backwards reads in order")
	TextBuffer.insert(buf, "X")
	assertEqual("oXree", TextBuffer.text(buf))
	assertEqual(nil, TextBuffer.selected(buf))
	TextBuffer.selectAll(buf)
	assertEqual("oXree", TextBuffer.cut(buf))
	assertEqual("", TextBuffer.text(buf))
	assertEqual(nil, TextBuffer.cut(buf), "nothing selected cuts nothing")
end)

test("arrows move by character across line ends; up and down keep the column; shift extends", function()
	local buf = TextBuffer.new("abc\nd\nefgh")
	TextBuffer.place(buf, 1, 3)
	TextBuffer.move(buf, "right")
	assertEqual(2, buf.line)
	assertEqual(0, buf.col)
	TextBuffer.move(buf, "left")
	assertEqual(1, buf.line)
	assertEqual(3, buf.col)
	TextBuffer.move(buf, "down")
	assertEqual(2, buf.line)
	assertEqual(1, buf.col, "held to the shorter line")
	TextBuffer.move(buf, "end")
	TextBuffer.move(buf, "down", true)
	assertEqual("\ne", TextBuffer.selected(buf))
	TextBuffer.move(buf, "home", true)
	assertEqual(0, buf.col)
	TextBuffer.move(buf, "up")
	assertEqual(nil, TextBuffer.selected(buf), "a plain move drops the selection")
	assertEqual(2, buf.line)
end)

test("display cells count a UTF-8 character as one and step tabs to every 4th cell", function()
	assertEqual(3, TextBuffer.cell("a\195\169b", 4))
	assertEqual(5, TextBuffer.cell("\tx", 2))
	assertEqual(4, TextBuffer.colAt("a\195\169bc", 3), "cell 3 is after the b")
	assertEqual(1, TextBuffer.colAt("\tx", 3), "inside a tab rounds to its nearer side")
	assertEqual(2, TextBuffer.colAt("\tx", 99), "past the end is the end")
end)
