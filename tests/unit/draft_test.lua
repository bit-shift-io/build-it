local Draft = require("src.game.builder.draft")
local Config = require("src.game.config")
local Model = require("src.game.blocks.model")

local CFG = Config.builder

test("a new draft is an empty 1x1 baseplate", function()
	local d = Draft.new()
	assertEqual(1, d.width)
	assertEqual(1, d.depth)
	assertEqual(0, #d.bricks)
end)

test("a brick placed on the baseplate occupies its 2x2 studs", function()
	local d = Draft.new()
	local brick = Draft.place(d, 1, 2, 0, CFG)
	assertTrue(brick, "expected the brick to be placed")
	assertEqual(brick, Draft.brickAt(d, 1, 2, 0))
	assertEqual(brick, Draft.brickAt(d, 2, 3, 0))
	assertEqual(nil, Draft.brickAt(d, 3, 2, 0))
	assertEqual(nil, Draft.brickAt(d, 1, 2, 1))
end)

test("placement is refused where the brick would hang off the baseplate", function()
	local d = Draft.new() -- 4x4 studs
	local brick, reason = Draft.place(d, 3, 0, 0, CFG)
	assertEqual(nil, brick)
	assertEqual("outside", reason)
	assertEqual(nil, (Draft.place(d, -1, 0, 0, CFG)))
	assertEqual(nil, (Draft.place(d, 0, 3, 0, CFG)))
	assertEqual(nil, (Draft.place(d, 0, 0, -1, CFG)))
	assertEqual(0, #d.bricks)
end)

test("placement is refused at or above the layer cap", function()
	local d = Draft.new()
	assertTrue(Draft.place(d, 0, 0, CFG.maxLayers - 1, CFG), "expected the top layer to be allowed")
	local brick, reason = Draft.place(d, 2, 0, CFG.maxLayers, CFG)
	assertEqual(nil, brick)
	assertEqual("too high", reason)
end)

test("placement is refused where it overlaps another brick", function()
	local d = Draft.new()
	Draft.place(d, 0, 0, 0, CFG)
	local brick, reason = Draft.place(d, 1, 1, 0, CFG)
	assertEqual(nil, brick)
	assertEqual("overlap", reason)
	assertTrue(Draft.place(d, 1, 1, 1, CFG), "expected a brick stacked half over it to fit")
	assertTrue(Draft.place(d, 2, 0, 0, CFG), "expected a brick flush beside it to fit")
	assertEqual(3, #d.bricks)
end)

test("removing a brick frees its studs", function()
	local d = Draft.new()
	local brick = Draft.place(d, 0, 0, 0, CFG)
	Draft.remove(d, brick)
	assertEqual(0, #d.bricks)
	assertEqual(nil, Draft.brickAt(d, 0, 0, 0))
	assertTrue(Draft.place(d, 1, 1, 0, CFG), "expected the freed studs to take a brick")
end)

test("the baseplate grows and shrinks within 1x1 to 4x4 tiles", function()
	local d = Draft.new()
	assertTrue(Draft.resize(d, 4, 3, CFG))
	assertEqual(4, d.width)
	assertEqual(3, d.depth)
	local ok, reason = Draft.resize(d, 5, 3, CFG)
	assertFalse(ok)
	assertEqual("size", reason)
	assertFalse((Draft.resize(d, 4, 0, CFG)))
	assertEqual(4, d.width)
	assertEqual(3, d.depth)
end)

test("shrinking is refused while a brick sits outside the new size", function()
	local d = Draft.new()
	Draft.resize(d, 2, 2, CFG)
	Draft.place(d, 4, 0, 0, CFG) -- on the second tile column
	local ok, reason = Draft.resize(d, 1, 2, CFG)
	assertFalse(ok)
	assertEqual("bricks", reason)
	assertEqual(2, d.width)
	assertTrue(Draft.resize(d, 2, 1, CFG), "expected the brick to stay inside a 2x1 baseplate")
end)

test("a draft becomes a stud-grid block model with one cell per brick stud", function()
	local d = Draft.new()
	Draft.resize(d, 2, 1, CFG)
	Draft.place(d, 0, 0, 0, CFG)
	Draft.place(d, 1, 1, 1, CFG)
	local m = Draft.toModel(d, CFG)
	assertEqual(CFG.studsPerTile, m.cellsPerTile)
	assertEqual(2, m.width)
	assertEqual(1, m.depth)
	assertEqual(8, #m.cells)
	local b = Model.bounds(m)
	assertEqual(0, b.minX)
	assertEqual(3, b.maxX)
	assertEqual(2, b.maxZ)
end)

test("fits answers whether a brick would place there, without placing it", function()
	local d = Draft.new()
	Draft.place(d, 0, 0, 0, CFG)
	assertTrue(Draft.fits(d, 2, 2, 0, CFG))
	local ok, reason = Draft.fits(d, 1, 1, 0, CFG)
	assertFalse(ok)
	assertEqual("overlap", reason)
	assertEqual(1, #d.bricks)
end)
